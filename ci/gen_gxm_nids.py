#!/usr/bin/env python3
"""Generate user/gxm_nids.h (NIDs of the SceGxm functions the GXM recon hooks use)
from the vita-headers NID database.

    gen_gxm_nids.py VITA_HEADERS_DB_DIR OUTPUT_HEADER
"""

import glob
import sys

import yaml

FUNCS = [
    "sceGxmCreateRenderTarget",
    "sceGxmColorSurfaceInit",
    "sceGxmDepthStencilSurfaceInit",
    "sceGxmSetViewport",
    "sceGxmSetRegionClip",
]


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    db_dir, out = sys.argv[1:]
    lib_nid, funcs = None, {}
    for f in glob.glob(db_dir + "/360/*.yml"):
        y = yaml.safe_load(open(f))
        for mod in (y.get("modules") or {}).values():
            for lname, lib in (mod.get("libraries") or {}).items():
                if lname == "SceGxm":
                    lib_nid = lib.get("nid")
                    funcs.update(lib.get("functions") or {})
    if lib_nid is None:
        sys.exit("SceGxm library not found in the database")
    missing = [n for n in FUNCS if n not in funcs]
    if missing:
        sys.exit("not in the database: " + ", ".join(missing))
    with open(out, "w") as o:
        o.write("/* generated by ci/gen_gxm_nids.py from vita-headers, do not edit */\n")
        o.write("#define GXM_LIB_NID 0x%08X\n" % lib_nid)
        for n in FUNCS:
            o.write("#define GXM_NID_%s 0x%08X\n" % (n, funcs[n]))
    print("wrote", out)


if __name__ == "__main__":
    main()
